import type { FC } from "react";
import type { SvgProps } from "react-native-svg";
import type { Achievement } from "@/api/achievements";
import { isStreakAchievement } from "@/features/achievements/streakTier";
import FirstLesson from "@assets/achievements/coins/FIRST_LESSON.svg";
import Lessons25 from "@assets/achievements/coins/LESSONS_25.svg";
import Lessons50 from "@assets/achievements/coins/LESSONS_50.svg";
import Lessons100 from "@assets/achievements/coins/LESSONS_100.svg";
import CourseMaster from "@assets/achievements/coins/COURSE_MASTER.svg";
import Courses3 from "@assets/achievements/coins/COURSES_3.svg";
import XpGrinder from "@assets/achievements/coins/XP_GRINDER.svg";
import Xp5000 from "@assets/achievements/coins/XP_5000.svg";
import Xp25000 from "@assets/achievements/coins/XP_25000.svg";
import Xp100000 from "@assets/achievements/coins/XP_100000.svg";
import WeeklyXp1000 from "@assets/achievements/coins/WEEKLY_XP_1000.svg";
import WeeklyXp3000 from "@assets/achievements/coins/WEEKLY_XP_3000.svg";
import FirstFriend from "@assets/achievements/coins/FIRST_FRIEND.svg";
import FirstGift from "@assets/achievements/coins/FIRST_GIFT.svg";
import GiftGiver from "@assets/achievements/coins/GIFT_GIVER.svg";
import FirstPurchase from "@assets/achievements/coins/FIRST_PURCHASE.svg";
import Shop5 from "@assets/achievements/coins/SHOP_5.svg";

type Criteria = Pick<Achievement, "criteriaType" | "criteriaValue">;

/**
 * Coin art per achievement, keyed by `criteriaType:criteriaValue` (the celebration screen only
 * receives those two, not the `code`). Generated by `design/achievement-coin/build-coins.mjs`.
 * Streak achievements are not here: they use the animated medal (`StreakMedal`).
 */
const COINS: Record<string, FC<SvgProps>> = {
  "LESSONS_COMPLETED:1": FirstLesson,
  "LESSONS_COMPLETED:25": Lessons25,
  "LESSONS_COMPLETED:50": Lessons50,
  "LESSONS_COMPLETED:100": Lessons100,
  "COURSES_COMPLETED:1": CourseMaster,
  "COURSES_COMPLETED:3": Courses3,
  "TOTAL_XP:500": XpGrinder,
  "TOTAL_XP:5000": Xp5000,
  "TOTAL_XP:25000": Xp25000,
  "TOTAL_XP:100000": Xp100000,
  "WEEKLY_XP:1000": WeeklyXp1000,
  "WEEKLY_XP:3000": WeeklyXp3000,
  "FRIENDS_COUNT:1": FirstFriend,
  "GIFTS_SENT:1": FirstGift,
  "GIFTS_SENT:5": GiftGiver,
  "SHOP_PURCHASES:1": FirstPurchase,
  "SHOP_PURCHASES:5": Shop5,
};

export function coinFor({ criteriaType, criteriaValue }: Criteria): FC<SvgProps> | null {
  return COINS[`${criteriaType}:${criteriaValue}`] ?? null;
}

/** True when the achievement has its own art (streak medal or coin); otherwise show the generic icon. */
export function hasAchievementArt(achievement: Criteria): boolean {
  return isStreakAchievement(achievement) || coinFor(achievement) !== null;
}
